#!/usr/bin/env bash
# Regenerates THIRD_PARTY_NOTICES.md from the modules linked into the binary
# (windows and linux builds) and saves their full license texts to
# dist/licenses/, which the release workflow zips next to the binaries. Run
# after changing go.mod; `notices.sh --check` (CI) fails if the committed file
# is stale. A repository with notices of its own, such as one that needs the
# source of GPL components, keeps its own script and does not use this one.
#
# Optional repository files:
#   notices-extra.md   table rows (| [name](url) | version | license |) added
#                      for what go-licenses cannot see (a bundled C library).
set -euo pipefail
export LC_ALL=C # sort the same everywhere
# shellcheck source=lib.sh
source "$(dirname "$0")/lib.sh"

check=0
[[ ${1:-} != --check ]] || check=1
target=THIRD_PARTY_NOTICES.md
if ((check)); then
  target=$(mktemp)
fi

# Build the tool once for this machine: GOOS set on 'go run' would build it
# for the target OS, which then cannot run here and silently reports nothing.
# GOOS set when running it selects the target build to analyse.
toolbin=$(mktemp -d)
trap 'rm -rf "$toolbin" "${tpl:-}" "${target_tmp:-}"' EXIT
GOBIN=$toolbin go install github.com/google/go-licenses/v2@v2.0.1
golicenses=$(ls "$toolbin"/go-licenses*)
self=$(go list -m)
tpl=$(mktemp)
printf '{{range .}}{{.Name}}\t{{.Version}}\t{{.LicenseName}}\n{{end}}' >"$tpl"

# go-licenses exits non-zero on mere warnings (e.g. on Windows) while still
# printing the full report, so judge by the output instead.
rows=$(
  for os in windows linux; do
    GOOS=$os $golicenses report --template "$tpl" "$MAIN_PKG" 2>/dev/null || true
  done | { grep -v "^$self" || true; } | sort -u
)
if [[ -z $rows ]]; then
  echo "notices.sh: go-licenses reported no modules" >&2
  exit 1
fi
if grep -F Unknown <<<"$rows" >&2; then
  echo "notices.sh: go-licenses could not identify the licenses above" >&2
  exit 1
fi
# go-licenses names packages; the license links take their modules.
modules=$(
  for os in windows linux; do
    GOOS=$os go list -deps -f '{{with .Module}}{{.Path}}{{end}}' "$MAIN_PKG"
  done | sort -u
)

own="$SERVER's own code is licensed under ${LICENSE_ID:-its repository license} (see [LICENSE](LICENSE))."
{
  cat <<EOF2
# Third-party notices

$own The binaries also contain
the code listed below, each under its own license. Every GitHub Release ships their full
license texts as \`${SERVER}_<version>_licenses.zip\`.

<!-- Generated by scripts/notices.sh — do not edit by hand. -->

| Component | Version | License |
|---|---|---|
| [Go standard library and runtime](https://go.dev/LICENSE) | toolchain | BSD-3-Clause |
EOF2
  [[ ! -f notices-extra.md ]] || cat notices-extra.md
  # One row per package path, linked to the licenses of its module (the
  # longest module path prefixing it); merge the licenses of dual-licensed
  # modules.
  awk -F'\t' -v modules="$modules" '
    BEGIN { split(modules, mods, "\n") }
    function module(pkg,   i, best) {
      for (i in mods) if ((pkg == mods[i] || index(pkg, mods[i] "/") == 1) && length(mods[i]) > length(best)) best = mods[i]
      return best
    }
    {
      key = $1 FS $2
      if (!(key in lic)) { lic[key] = $3; order[++n] = key }
      else if (index(lic[key], $3) == 0) lic[key] = lic[key] " AND " $3
    }
    END {
      for (i = 1; i <= n; i++) {
        split(order[i], k, FS)
        if ((m = module(k[1])) == "") { print "notices.sh: no module for " k[1] >"/dev/stderr"; exit 1 }
        printf "| [%s](https://pkg.go.dev/%s@%s?tab=licenses) | %s | %s |\n", k[1], m, k[2], k[2], lic[order[i]]
      }
    }
  ' <<<"$rows"
} >"$target"

if ((check)); then
  target_tmp=$target
  cmp -s "$target" THIRD_PARTY_NOTICES.md ||
    { echo "notices.sh: THIRD_PARTY_NOTICES.md is stale, run the kit's scripts/notices.sh and commit" >&2; exit 1; }
  echo "THIRD_PARTY_NOTICES.md is up to date"
  exit 0
fi

rm -rf dist/licenses
for os in windows linux; do
  GOOS=$os $golicenses save "$MAIN_PKG" --save_path "dist/licenses-$os" --ignore "$self" --force 2>/dev/null || true
done
mkdir -p dist/licenses/golang.org/go
for d in dist/licenses-windows dist/licenses-linux; do
  [[ -d $d ]] && cp -rf "$d/." dist/licenses/ # -f: go-licenses saves read-only files
done
cp "$(go env GOROOT)/LICENSE" dist/licenses/golang.org/go/LICENSE # stdlib and runtime
rm -rf dist/licenses-windows dist/licenses-linux dist/licenses/"$self"
echo "THIRD_PARTY_NOTICES.md: $(grep -c '^| \[' THIRD_PARTY_NOTICES.md) components; license texts in dist/licenses/"
